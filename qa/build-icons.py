#!/usr/bin/env python3
"""
build-icons.py — regenerates every app icon from the master badge artwork.

Source of truth: icons/src-badge-512.png (512x512: blue rounded badge with the
white Z-arrows glyph, on an opaque off-white canvas — the original export).

Why this exists: the shipped maskable icon used to be that same export pasted
inset on a white canvas, so Android's own PWA launch screen (generated by
Chrome from the manifest BEFORE any web code runs) showed the badge floating
in an ugly white box. A real maskable icon must be full-bleed with the key
glyph inside the central safe zone. The "any" icons also carried opaque
off-white corners instead of transparency.

Outputs (all derived from the one master, so every surface matches):
  icons/maskable-512.png  full-bleed badge-blue gradient + glyph @ safe size
  icons/icon-512.png      rounded badge, transparent corners (purpose: any)
  icons/icon-192.png      same, 192px (also apple-touch-icon)
  icons/splash-logo.png   216px badge used by the in-page boot splash, so the
                          Chrome launch screen and our loading page show the
                          SAME logo and read as one continuous screen

Run:  python3 qa/build-icons.py     (needs Pillow; not part of npm/CI)
After regenerating, bump the ?v= on manifest icon srcs + the SW cache so
installed WebAPKs actually refetch the new artwork.
"""
from PIL import Image, ImageDraw
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = os.path.join(ROOT, 'icons', 'src-badge-512.png')
SS = 4  # supersample factor for smooth masks


def rounded_mask(size, radius):
    """Anti-aliased rounded-rect alpha mask (L mode)."""
    big = Image.new('L', (size * SS, size * SS), 0)
    d = ImageDraw.Draw(big)
    d.rounded_rectangle([0, 0, size * SS - 1, size * SS - 1], radius=radius * SS, fill=255)
    return big.resize((size, size), Image.LANCZOS)


def vertical_gradient(size, top, bottom):
    grad = Image.new('RGB', (1, size))
    for y in range(size):
        t = y / (size - 1)
        grad.putpixel((0, y), tuple(round(top[i] + (bottom[i] - top[i]) * t) for i in range(3)))
    return grad.resize((size, size))


def main():
    src = Image.open(SRC).convert('RGB')
    W = src.size[0]
    assert src.size == (512, 512), src.size

    # Badge blues sampled from the master (top / bottom of the badge face).
    top_blue = src.getpixel((W // 2, int(W * 0.06)))
    bot_blue = src.getpixel((W // 2, int(W * 0.95)))
    print('badge gradient:', top_blue, '->', bot_blue)

    # --- extract the white glyph as an alpha layer -------------------------
    # Whiteness = min(r,g,b): badge blue is ~10, glyph is 255, the off-white
    # corner fill is ~240 — so confine extraction to the badge's rounded
    # shape (inset a touch) to keep the corners out.
    px = src.load()
    alpha = Image.new('L', (W, W), 0)
    ap = alpha.load()
    for y in range(W):
        for x in range(W):
            m = min(px[x, y])
            a = (m - 40) / (235 - 40)
            ap[x, y] = 0 if a <= 0 else 255 if a >= 1 else int(a * 255)
    badge_area = rounded_mask(W, int(W * 0.235))
    # shrink the allowed area slightly so badge-edge anti-aliasing stays out
    inner = Image.new('L', (W, W), 0)
    inset = 10
    inner.paste(badge_area.crop((inset, inset, W - inset, W - inset)).resize((W - 2 * inset, W - 2 * inset)), (inset, inset))
    alpha = Image.composite(alpha, Image.new('L', (W, W), 0), inner)

    # The badge's own anti-aliased rim against the off-white canvas is ALSO
    # near-white, so whiteness alone leaks a rim ghost. Keep only the white
    # component connected to the image centre (the glyph), dilated a couple
    # of px so the glyph's own soft edge ramp survives.
    from PIL import ImageFilter
    whiteish = [[min(px[x, y]) >= 170 for x in range(W)] for y in range(W)]
    seen = [[False] * W for _ in range(W)]
    stack = [(W // 2, W // 2)]
    seen[W // 2][W // 2] = True
    comp = Image.new('L', (W, W), 0)
    cp = comp.load()
    while stack:
        x, y = stack.pop()
        cp[x, y] = 255
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < W and 0 <= ny < W and not seen[ny][nx] and whiteish[ny][nx]:
                seen[ny][nx] = True
                stack.append((nx, ny))
    allowed = comp.filter(ImageFilter.MaxFilter(5))
    alpha = Image.composite(alpha, Image.new('L', (W, W), 0), allowed)

    bbox = alpha.point(lambda v: 255 if v > 127 else 0).getbbox()
    glyph = Image.new('RGBA', (W, W), (255, 255, 255, 0))
    glyph.putalpha(alpha)
    glyph = glyph.crop(bbox)
    gw, gh = glyph.size
    print(f'glyph bbox in master: {gw}x{gh} ({gw / W:.0%} x {gh / W:.0%})')

    def compose(glyph_width):
        """Full-bleed gradient + centered glyph at the given px width."""
        canvas = vertical_gradient(W, top_blue, bot_blue).convert('RGBA')
        scale = glyph_width / gw
        g = glyph.resize((glyph_width, round(gh * scale)), Image.LANCZOS)
        canvas.alpha_composite(g, ((W - g.size[0]) // 2, (W - g.size[1]) // 2))
        return canvas

    def save(img, name):
        path = os.path.join(ROOT, 'icons', name)
        img.save(path, optimize=True)
        print('wrote', path, img.size, f'{os.path.getsize(path) // 1024}KB')

    # --- maskable: glyph tips must survive even a circular system mask ----
    # Keep the Z's corner tips inside the 80%-diameter safe circle:
    # half-diag of the glyph bbox <= 40% of canvas. 296px wide does it.
    save(compose(296), 'maskable-512.png')

    # --- "any" badge: fuller glyph, rounded corners, real transparency ----
    badge = compose(318)
    badge.putalpha(rounded_mask(W, int(W * 0.235)))
    save(badge, 'icon-512.png')
    save(badge.resize((192, 192), Image.LANCZOS), 'icon-192.png')

    # --- boot-splash logo: the 72px badge at 3x ----------------------------
    save(badge.resize((216, 216), Image.LANCZOS), 'splash-logo.png')
    print('ICONS DONE')


if __name__ == '__main__':
    main()
