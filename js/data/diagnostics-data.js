/* Diagnostic reasoning normalization. Existing flows are preserved, while each
   node receives an explicit TEST/WHY/EXPECTED/IF NORMAL/IF ABNORMAL/NEXT STEP
   contract. Numeric or model-specific statements are audit metadata only and
   are not promoted to verified universal facts. */
