var LANG = localStorage.getItem('zlift_lang') || 'fa';
function t(key) { return (I18N[LANG] && I18N[LANG][key]) || I18N.fa[key] || key; }
function faNum(n) {
  if (LANG !== 'fa') return String(n);
  return String(n).replace(/[0-9]/g, d => '۰۱۲۳۴۵۶۷۸۹'[d]);
}
function fmtDate(ts) {
  const d = new Date(ts);
  try {
    return new Intl.DateTimeFormat(LANG === 'fa' ? 'fa-IR' : 'en-GB', { year: 'numeric', month: 'short', day: 'numeric' }).format(d);
  } catch (e) { return d.toLocaleDateString(); }
}
function fmtDateTime(ts) {
  const d = new Date(ts);
  try {
    return new Intl.DateTimeFormat(LANG === 'fa' ? 'fa-IR' : 'en-GB', { year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' }).format(d);
  } catch (e) { return d.toLocaleString(); }
}
